//! The Welling's characters: one module per person in the scrap zone, each with its own
//! state and program, all placeholders for Ian to rewrite. The world's rules are in
//! `docs/worlds/welling/principles.md`; the people in `docs/worlds/welling/people.md`.
//!
//! A character answers the triggers that are theirs and passes the rest (`None`) to the
//! behaviour everyone in the Welling shares (`toolbox::human`).

