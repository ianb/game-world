use rand_pcg::Pcg32;
use serde::{Deserialize, Serialize};
use sim::brain::{CharacterSet, Command, Ctx, Planned, Trigger, baseline_plan};
use sim::ids::VillagerId;
use sim::social::Interlocutor;

/// What a character module provides. `ID` is the person's id in content.
pub trait Character: Interlocutor {
    const ID: &'static str;

    /// The day's plan: the content schedule, unless the character changes it.
    fn plan_day(&mut self, ctx: &Ctx<'_>, _rng: &mut Pcg32) -> Vec<Planned> {
        let me = ctx.villager_id(Self::ID).expect("character is in content");
        toolbox::Plan::baseline(me, ctx).build()
    }

    /// The character's own answer to a trigger, or `None` for the shared behaviour.
    fn react(&mut self, trigger: &Trigger, ctx: &Ctx<'_>, rng: &mut Pcg32) -> Option<Vec<Command>>;
}

/// `Character` without its constant, so the city can hold any of them behind one pointer.
trait Dispatch: Interlocutor {
    fn plan(&mut self, ctx: &Ctx<'_>, rng: &mut Pcg32) -> Vec<Planned>;
    fn answer(&mut self, trigger: &Trigger, ctx: &Ctx<'_>, rng: &mut Pcg32)
    -> Option<Vec<Command>>;
}

impl<T: Character> Dispatch for T {
    fn plan(&mut self, ctx: &Ctx<'_>, rng: &mut Pcg32) -> Vec<Planned> {
        Character::plan_day(self, ctx, rng)
    }
    fn answer(
        &mut self,
        trigger: &Trigger,
        ctx: &Ctx<'_>,
        rng: &mut Pcg32,
    ) -> Option<Vec<Command>> {
        Character::react(self, trigger, ctx, rng)
    }
}

/// Declares the city: one field per person, named by their content id, and the lookup
/// from id to character.
macro_rules! city {
    ($($id:ident: $ty:ty),* $(,)?) => {
        /// Every character in the Welling, by id.
        #[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
        pub struct City {
            $(pub $id: $ty,)*
        }

        impl City {
            fn character(&mut self, id: &str) -> Option<&mut dyn Dispatch> {
                Some(match id {
                    $(stringify!($id) => &mut self.$id,)*
                    _ => return None,
                })
            }

            fn character_ref(&self, id: &str) -> Option<&dyn Dispatch> {
                Some(match id {
                    $(stringify!($id) => &self.$id,)*
                    _ => return None,
                })
            }
        }
    };
}

city! {
    // The Mire: the refinery hulk.
    ora: ora::Ora,
    sab: sab::Sab,
    // The yard and the shanties.
    tully: tully::Tully,
    grue: grue::Grue,
    pike: pike::Pike,
    // The south raft and the tug.
    nessa: nessa::Nessa,
    hobb: hobb::Hobb,
    // The Kettle.
    lark: lark::Lark,
}

impl CharacterSet for City {
    /// Bump when any character struct changes shape.
    const LAYOUT_VERSION: u32 = 1;
    const BEHAVIOR: u64 = behavior::BEHAVIOR;

    fn new(content: &content::Content, _world: &content::World) -> Self {
        // The Welling keeps no animals yet; a kind declared here would need a decision
        // from every character first, as the valley's `Animal` does.
        assert!(
            content.animals.is_empty(),
            "the Welling's characters know no animals"
        );
        City::default()
    }

    fn plan_day(&mut self, who: VillagerId, ctx: &Ctx<'_>, rng: &mut Pcg32) -> Vec<Planned> {
        match self.character(ctx.villager(who).id.as_str()) {
            Some(c) => c.plan(ctx, rng),
            None => baseline_plan(who, ctx),
        }
    }

    fn react(
        &mut self,
        who: VillagerId,
        trigger: Trigger,
        ctx: &Ctx<'_>,
        rng: &mut Pcg32,
    ) -> Vec<Command> {
        let id = ctx.villager(who).id.as_str();
        self.character(id)
            .and_then(|c| c.answer(&trigger, ctx, rng))
            .unwrap_or_else(|| toolbox::human(&trigger, ctx, id))
    }

    fn interlocutor(&mut self, who: VillagerId, ctx: &Ctx<'_>) -> Option<&mut dyn Interlocutor> {
        self.character(ctx.villager(who).id.as_str())
            .map(|c| c as &mut dyn Interlocutor)
    }

    fn interlocutor_ref(&self, who: VillagerId, ctx: &Ctx<'_>) -> Option<&dyn Interlocutor> {
        self.character_ref(ctx.villager(who).id.as_str())
            .map(|c| c as &dyn Interlocutor)
    }
}
