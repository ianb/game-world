impl CharacterSet for Town {
    /// Bump when any character struct changes shape.
    const LAYOUT_VERSION: u32 = 10;
    const BEHAVIOR: u64 = behavior::BEHAVIOR;

    fn new(_content: &content::Content, _world: &content::World) -> Self {
        Town::default()
    }

    fn plan_day(&mut self, who: VillagerId, ctx: &Ctx<'_>, rng: &mut Pcg32) -> Vec<Planned> {
        match self.character(ctx.villager(who).id.as_str()) {
            Some(c) => c.plan(ctx, rng),
            None => baseline_plan(who, ctx),
        }
    }

    fn react(
        &mut self,
        who: VillagerId,
        trigger: Trigger,
        ctx: &Ctx<'_>,
        rng: &mut Pcg32,
    ) -> Vec<Command> {
        let id = ctx.villager(who).id.as_str();
        // Each character answers what is theirs; anything they pass on (`None`) gets the
        // behaviour every villager shares.
        let own = self
            .character(id)
            .and_then(|c| c.answer(&trigger, ctx, rng));
        let mut cmds = match (own, &trigger) {
            (Some(own), _) => own,
            (None, Trigger::Animals { kind, owner }) => {
                let fondness = self
                    .character_ref(id)
                    .map_or(Fondness::Indifferent, |c| c.fond(*kind));
                toolbox::meet_animals(ctx, who, *kind, *owner, fondness)
            }
            (None, _) => toolbox::human(&trigger, ctx, id),
        };
        // Shared rules that run alongside each character's own answer.
        if let Trigger::TalkEnded { other, .. } | Trigger::Encounter { other } = &trigger
            && let Some(mind) = self.interlocutor_ref(who, ctx)
        {
            cmds.extend(toolbox::kindness(ctx, who, *other, mind));
        }
        cmds
    }

    fn interlocutor(&mut self, who: VillagerId, ctx: &Ctx<'_>) -> Option<&mut dyn Interlocutor> {
        self.character(ctx.villager(who).id.as_str())
            .map(|c| c as &mut dyn Interlocutor)
    }

    fn interlocutor_ref(&self, who: VillagerId, ctx: &Ctx<'_>) -> Option<&dyn Interlocutor> {
        self.character_ref(ctx.villager(who).id.as_str())
            .map(|c| c as &dyn Interlocutor)
    }
}
