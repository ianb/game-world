/// How someone takes to a kind of animal. The shared response is in
/// `toolbox::meet_animals`; a character can answer `Trigger::Animals` itself instead.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum Fondness {
    /// Glad to see them: says so.
    Delighted,
    /// Pleased, quietly.
    Fond,
    Indifferent,
    /// Uneasy, quietly.
    Wary,
    /// Put out, and says so, laying it at the owner's door.
    Annoyed,
    /// Frightened: says so.
    Afraid,
}

/// What a character module provides. `ID` is the villager's id in content.
pub trait Character: Interlocutor {
    const ID: &'static str;

    /// How they take to each kind of animal. Every character decides; a new kind of animal
    /// makes each of them decide again.
    fn fondness(&self, kind: AnimalKind) -> Fondness;

    /// The day's plan: the content schedule, unless the character changes it.
    fn plan_day(&mut self, ctx: &Ctx<'_>, _rng: &mut Pcg32) -> Vec<Planned> {
        let me = ctx.villager_id(Self::ID).expect("character is in content");
        toolbox::Plan::baseline(me, ctx).build()
    }

    /// The character's own answer to a trigger, or `None` for the behaviour everyone
    /// shares (`toolbox::human`).
    fn react(&mut self, trigger: &Trigger, ctx: &Ctx<'_>, rng: &mut Pcg32) -> Option<Vec<Command>>;
}

/// `Character` without its constant, so the town can hold any of them behind one pointer.
trait Dispatch: Interlocutor {
    fn fond(&self, kind: AnimalKind) -> Fondness;
    fn plan(&mut self, ctx: &Ctx<'_>, rng: &mut Pcg32) -> Vec<Planned>;
    fn answer(&mut self, trigger: &Trigger, ctx: &Ctx<'_>, rng: &mut Pcg32)
    -> Option<Vec<Command>>;
}

impl<T: Character> Dispatch for T {
    fn fond(&self, kind: AnimalKind) -> Fondness {
        Character::fondness(self, kind)
    }
    fn plan(&mut self, ctx: &Ctx<'_>, rng: &mut Pcg32) -> Vec<Planned> {
        Character::plan_day(self, ctx, rng)
    }
    fn answer(
        &mut self,
        trigger: &Trigger,
        ctx: &Ctx<'_>,
        rng: &mut Pcg32,
    ) -> Option<Vec<Command>> {
        Character::react(self, trigger, ctx, rng)
    }
}

/// Declares the town: one field per villager, named by their content id, and the lookup
/// from id to character. Adding a villager is a line here and a module.
macro_rules! town {
    ($($id:ident: $ty:ty),* $(,)?) => {
        /// Every character in the town, by id.
        #[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
        pub struct Town {
            $(pub $id: $ty,)*
        }

        impl Town {
            fn character(&mut self, id: &str) -> Option<&mut dyn Dispatch> {
                Some(match id {
                    $(stringify!($id) => &mut self.$id,)*
                    _ => return None,
                })
            }

            fn character_ref(&self, id: &str) -> Option<&dyn Dispatch> {
                Some(match id {
                    $(stringify!($id) => &self.$id,)*
                    _ => return None,
                })
            }
        }
    };
}

