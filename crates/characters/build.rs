//! Fingerprints the code that decides behavior: this crate, the sim and the content
//! compiler. A snapshot records the fingerprint, and a snapshot made under different rules
//! is refused, because replaying it would not reproduce what happened.
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            rust_files(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
}

/// FNV-1a, 64-bit: enough to tell versions apart, and no build dependency.
fn fnv(hash: &mut u64, bytes: &[u8]) {
    for b in bytes {
        *hash ^= u64::from(*b);
        *hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
}

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let dirs = [
        root.join("src"),
        root.join("../sim/src"),
        root.join("../content/src"),
    ];
    let mut files = Vec::new();
    for dir in &dirs {
        println!("cargo:rerun-if-changed={}", dir.display());
        rust_files(dir, &mut files);
    }
    // Sort by path relative to the workspace so the fingerprint does not depend on where
    // the checkout lives or on directory order.
    let mut named: Vec<(String, PathBuf)> = files
        .into_iter()
        .map(|p| {
            let rel = p
                .strip_prefix(root.join(".."))
                .map_or_else(|_| p.display().to_string(), |r| r.display().to_string());
            (rel.replace('\\', "/").replace("characters/../", ""), p)
        })
        .collect();
    named.sort();
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for (name, path) in &named {
        fnv(&mut hash, name.as_bytes());
        fnv(&mut hash, &fs::read(path).expect("readable source file"));
    }
    let mut code = String::new();
    let _ = writeln!(
        code,
        "/// Fingerprint of the behavior code ({} files). Generated by build.rs.",
        named.len()
    );
    let hex = format!("{hash:016x}");
    let _ = writeln!(
        code,
        "pub const BEHAVIOR: u64 = 0x{}_{}_{}_{};",
        &hex[0..4],
        &hex[4..8],
        &hex[8..12],
        &hex[12..16]
    );
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("set by cargo")).join("behavior.rs");
    fs::write(out, code).expect("writable OUT_DIR");
}
